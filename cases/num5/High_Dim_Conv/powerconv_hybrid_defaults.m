function opts = powerconv_hybrid_defaults(opts)
% Default options shared by hybrid convolution routines.

if nargin < 1
    opts = struct();
end

defaults = struct( ...
    'mode', 'auto', ...
    'max_1d_p2', 64, ...
    'max_1d_p3', 32, ...
    'max_2d_double_p2', 8, ...
    'max_2d_double_p3', 8, ...
    'max_2d_interval_point_p2', 4, ...
    'max_2d_interval_point_p3', 4, ...
    'max_2d_interval_wide_p2', 8, ...
    'max_2d_interval_wide_p3', 6);

fields = fieldnames(defaults);
for k = 1:numel(fields)
    name = fields{k};
    if ~isfield(opts, name)
        opts.(name) = defaults.(name);
    end
end
end

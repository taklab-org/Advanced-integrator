% Projected BVP (MI 4 -> 3) for the 2D Ohta--Kawasaki equation.
% Revision 2026-10-09 (previous version: old/before_fix_20261009/):
%  (i)   Z contains the phase contribution 2 W_i^theta r^theta of eq:Z_BVP,
%        and the radii test is Y^i + Z^i(r) max_j r^j < r^i (thm:BVP_existence).
%  (ii)  Phase 4 uses the additive endpoint-remainder composition of Section 3
%        (verify_solution/pbvp_phase4.m, same algorithm as 2D-OK/try_phase4.m).
%  (iii) The trajectory is measured in X = max of the step norms X_m:
%        Z-tilde uses every row of W_Yq, ||g^u||_X = max_m Y_m, and U_DP is
%        the X-norm of U(.,0)V^u over all steps (not its endpoint value).
% Endpoint traces are exact interval traces of the stored polynomials, and all
% finite state vectors use the cosine weights 2^{#nonzero indices} nu^{|k|}.
% Shared bounds (coupling vectors, integrated semigroup, tail Volterra bounds,
% Chebyshev extrema) are the corrected 2D-OK versions.
% Run serially from a bootstrap that has initialized and checked INTLAB.

% Candidate data are regenerated by run_case in the output directory.
ai_add_case_paths(getenv('AI_CASE_ROOT'));
load(fullfile(getenv('GE_VERIFIED_RUN_DIR'),'pathdata4to3.mat'));
N1 = N(1); N2 = N(2);
% truncated Fourier dimensions for variational problem
m = [3,3]; m1 = m(1); m2 = m(2); m1m2 = prod(m);
% Integrate from 0 to tau
tau1_default = 2^-5;
num_partition_tmp = floor(tau/tau1_default) + 100;
nu = 1.0; % weight for norm of sequence
tspan = [0,tau1_default];
%
theta = x(1:udim);
phi = x(udim+1:end);
delta_iv = intval('0.01'); % phase radius delta = 0.01 (exact decimal)
assert(abs(delta - 0.01) < 1e-15);
%
% Initial sequence: Fourier is column in this code (including the zero mode)
DP = [v1u,v2u,v3u,v4u];
a0_init = [params(1); DP*theta];                       % Newton candidate
a0_exact = [intval(params(1)); intval(DP)*intval(theta)]; % P(bar theta)
alin_init = [zeros(1,udim); DP];
alin_exact = intval(alin_init);
%
% State weights (zero mode removed): w_k = 2^{[k1>0]+[k2>0]} nu^{k1+k2}
[k1s,k2s] = ind2sub(N, (2:N1*N2)');
k1s = k1s-1; k2s = k2s-1;
w_state = intval(2).^((k1s>0)+(k2s>0)) .* intval(nu).^(k1s+k2s);
wnorm_state = @(v) sum(w_state.*abs(v));
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Getting numerical data
%%%%%%%%%%%%%%%%%%%%%%%%%%%
disp('Compute linearized flow for Z bound ....')
[Y_lin1, Y_lin2, Y_lin3, Y_lin4] = getting_flow_fromDP(params,N,L,Y,DP,tau);
%
F2ba_fin_vec = intval(zeros(num_partition_tmp,1));
F2ba_inf_vec = intval(zeros(num_partition_tmp,1));
F1ba_fin_vec = intval(zeros(num_partition_tmp,1));
F1ba_inf_vec = intval(zeros(num_partition_tmp,1));
F1_lin_vec = intval(zeros(num_partition_tmp,udim));
F2_lin_vec = intval(zeros(num_partition_tmp,udim));
Xnorm_lin_vec = intval(zeros(num_partition_tmp,udim));
tau_vec = zeros(num_partition_tmp,1);
ba_vec = cell(num_partition_tmp,1);
banorm_vec = intval(zeros(num_partition_tmp,1));
VinfJ_vec = intval(zeros(num_partition_tmp,1));
VinfqJ_vec = intval(zeros(num_partition_tmp,1));
g22_vec = intval(zeros(num_partition_tmp,1));
int_semi_vec = cell(num_partition_tmp,1);
int_semi_q_vec = cell(num_partition_tmp,1);
psi_vec_store = cell(num_partition_tmp,1);
c_out_store = cell(num_partition_tmp,1);
n_cheb_vec = zeros(num_partition_tmp,1);
%
[kx_w, ky_w] = ndgrid(0:m1-1, 0:m2-1);
alp_2d = 4*ones(m1, m2); alp_2d(1,:) = 2; alp_2d(:,1) = 2; alp_2d(1,1) = 1;
w_fin = alp_2d(:) .* nu.^kx_w(:) .* nu.^ky_w(:);
D_w = diag(intval(w_fin));
D_w_inv = diag(intval(1./w_fin));
%
one_sided_trace = @(c) reshape(c(1,:,:) + 2*sum(c(2:end,:,:),1), [], 1);
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Refine data with Newton & defects of eqs.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
disp('Refine numerical data with Newton ....')
timestep = 1; tau1 = tau1_default;
trace_prev = a0_exact;            % exact left datum of the current step
trace_lin_prev = alin_exact;      % same for the four linearized flows
while timestep <= num_partition_tmp
  disp(['*** timestep: ',num2str(timestep),' / tspan = [',num2str(tspan(1)),', ',num2str(tspan(2)),'] ***'])
  [ba, defect, a_end] = getting_the_solution(N,tspan,a0_init,Y,params,L);
  %
  [int_semi_mat, int_semi_mat_q, ba2_sup_ts] = getting_int_semi_matrix(ba, tau1, m, params, L, nu);
  [VinfJ, VinfqJ, mu_m] = getting_Vinf(tau1,N,m,params,L);
  [psi_vec_ts, c_out_per_mode_ts] = getting_coupling_vectors(ba2_sup_ts, m, N, nu);
  g22 = VinfqJ*3*wnorm(ba2_sup_ts,nu);
  c_in_w = D_w * (abs(int_semi_mat_q) * (3 * psi_vec_ts));
  c_out_w = (D_w_inv * (VinfqJ * 3 * c_out_per_mode_ts))';
  schur = intval(1) - g22 - c_out_w * c_in_w;
  if ~(inf(schur) > 0)
    disp('Schur complement is not positive: adjust time steps')
    tau1 = 0.8*tau1;
    tspan(2) = tspan(1) + tau1;
    continue
  end
  %
  tau_vec(timestep) = tau1;
  n_cheb_vec(timestep) = size(ba,1);
  ba_vec{timestep} = ba;
  ba_sup = reshape(chebmag_oneside(reshape(ba, size(ba,1), N1*N2)), N1, N2);
  banorm_vec(timestep) = wnorm(ba_sup, nu);
  F1ba_fin_vec(timestep) = wnorm(defect(:,1:m1,1:m2),nu); defect(:,1:m1,1:m2) = 0;
  F1ba_inf_vec(timestep) = wnorm(defect,nu);
  %
  % Linearized flows U(t,0)v_i^u along bar u
  [ba_lin1, ba_lin2, ba_lin3, ba_lin4, idefect_lin, UDP] = getting_the_solution_linear(ba,N,tspan,alin_init,Y_lin1,Y_lin2,Y_lin3,Y_lin4,params,L,nu);
  ba_lin = {ba_lin1, ba_lin2, ba_lin3, ba_lin4};
  F1_lin_vec(timestep,:) = idefect_lin;
  disp(['||F_1(\bar{a})|| = ',num2str(sup(F1ba_fin_vec(timestep) + F1ba_inf_vec(timestep)))])
  disp(['defect of linearized PDEs: ',num2str(sup(idefect_lin))])
  %
  % F2: left value minus the EXACT trace of the previous polynomial
  vepsilon = compute_eps2(intval(ba), trace_prev);
  F2ba_fin_vec(timestep) = wnorm(vepsilon(1:m1,1:m2),nu); vepsilon(1:m1,1:m2) = 0;
  F2ba_inf_vec(timestep) = wnorm(vepsilon,nu);
  trace_prev = one_sided_trace(intval(ba));
  trace_lin_now = intval(zeros(N1*N2,udim));
  for i = 1:udim
    F2_lin_vec(timestep,i) = compute_eps(intval(ba_lin{i}), trace_lin_prev(:,i), nu);
    trace_lin_now(:,i) = one_sided_trace(intval(ba_lin{i}));
    nl = size(ba_lin{i},1);
    Xnorm_lin_vec(timestep,i) = wnorm(reshape(chebmag_oneside(reshape(intval(ba_lin{i}),nl,N1*N2)),N1,N2),nu);
  end
  trace_lin_prev = trace_lin_now;
  disp(['||F_2(\bar{a})|| = ',num2str(sup(F2ba_fin_vec(timestep) + F2ba_inf_vec(timestep)))])
  disp(['defect at section: ',num2str(sup(F2_lin_vec(timestep,:)))])
  %
  VinfJ_vec(timestep) = VinfJ;
  VinfqJ_vec(timestep) = VinfqJ;
  g22_vec(timestep) = g22;
  int_semi_vec{timestep} = int_semi_mat;
  int_semi_q_vec{timestep} = int_semi_mat_q;
  psi_vec_store{timestep} = psi_vec_ts;
  c_out_store{timestep} = c_out_per_mode_ts;
  %
  if tspan(2)>=tau
    num_integration = timestep;
    break
  end
  tau1 = tau1_default;
  timestep = timestep + 1;
  tspan(1) = tspan(2);
  tspan(2) = tspan(2) + tau1;
  if tspan(2) > tau
    tspan(2) = tau;
    tau1 = tspan(2) - tspan(1);
  end
  a0_init = a_end;
  alin_init = UDP;
end
if timestep == num_partition_tmp
  error('reach max time steps')
end
K = num_integration;
fprintf('steps K=%d, tau_vec=%s, Chebyshev orders=%s\n', K, mat2str(tau_vec(1:K)'), mat2str(n_cheb_vec(1:K)'));
%%
disp('Solve variational problem on each timestep ....')
bUn_vec = cell(K,1); bUn_endpt_vec = cell(K,1); r1_vec = intval(zeros(K,m1m2));
tic
for timestep = 1:K
  [bUn, r1] = verify_variationaleq(ba_vec{timestep},tau_vec(timestep),m,params,L);
  assert(all(isfinite(sup(r1))) && all(inf(r1) >= 0), 'Variational enclosure failed at step %d', timestep);
  bUn_vec{timestep} = bUn;
  bUn_endpt_vec{timestep} = getting_Un_endpt(bUn,r1);
  r1_vec(timestep,:) = r1;
end
toc
%% Phase 4: additive endpoint-remainder composition
fprintf('\n=== Phase 4: additive endpoint-remainder composition (K=%d, m=[%d,%d]) ===\n', K, m1, m2);
P4 = pbvp_phase4(bUn_vec, bUn_endpt_vec, r1_vec, ...
  int_semi_vec(1:K), int_semi_q_vec(1:K), psi_vec_store(1:K), c_out_store(1:K), g22_vec(1:K), ...
  VinfJ_vec(1:K), VinfqJ_vec(1:K), F1ba_fin_vec(1:K), F1ba_inf_vec(1:K), ...
  F2ba_fin_vec(1:K), F2ba_inf_vec(1:K), banorm_vec(1:K), tau_vec(1:K), mu_m, m, nu);
Y_sup = P4.Y_sup; W_ell = P4.W_ell; W_Y = P4.W_Y; W_Yq = P4.W_Yq;
fprintf('  min Schur = %.6e\n', min(inf(P4.schur)));
fprintf('  max r1 (variational) = %.6e\n', max(sup(r1_vec(:))));
fprintf('  ||U(t,0)|| (W_ell(K,1)) = %.6e\n', sup(W_ell(K,1)));
fprintf('  Y_m = %s\n', mat2str(sup(Y_sup)',5));
if P4.ivp.passed
  fprintf('IVP PART: r = %.6e, Z = %.6e (all P_m<0)\n', P4.ivp.max_r, P4.ivp.max_Z);
else
  fprintf('IVP PART: radii test FAILED\n');
end
%
%% Linearized flows: errors and U_DP in the X norm
% err(m,i) bounds ||U(.,0)v_i - p_i||_{X_m}; Duhamel with the same U, V tables.
err_lin = W_ell*F2_lin_vec(1:K,:) + W_Y*F1_lin_vec(1:K,:);
err_end = err_lin(K,:);                         % endpoint error, each column
U_DP = max(max(sup(Xnorm_lin_vec(1:K,:) + err_lin)));
fprintf('  linear flow errors (endpoint) = %s\n', mat2str(sup(err_end),5));
fprintf('  U_DP (X norm, all steps) = %.6e\n', U_DP);
%
%% Reduced endpoint operator and its approximate inverse
sdim_fin = length(phi);
assert(size(Vs_at_ta,1) == N1*N2-1 && size(Vs_at_ta,2) == sdim_fin);
wphi = w_state(1:sdim_fin);
% Enclosure of Pi^N U(tau,0)V^u: exact traces +/- endpoint errors (entrywise)
iUend = trace_lin_prev(2:end,:) + (intval(sup(err_end)) ./ w_state) .* infsup(-1,1);
Bdag_fin = [2*intval(theta).', intval(zeros(1,sdim_fin)); iUend, -intval(Vs_at_ta)];
B = inv(mid(Bdag_fin));          % chosen numerical inverse (exact floats)
iB = intval(B);
R0 = intval(eye(udim+sdim_fin)) - iB*Bdag_fin;
it = 1:udim; ip = udim+1:udim+sdim_fin;
aR = abs(R0);
Z0_mat = [max(sum(aR(it,it),1)), max(sum(aR(it,ip),1)./wphi.'); ...
          max(sum(wphi.*aR(ip,it),1)), max(sum(wphi.*aR(ip,ip),1)./wphi.')];
% B(barB^dag - B^dag) = [0; -Pi^inf U(tau,0)V^u] (B is -I on the tail)
Z1_mat = [intval(0), intval(0); max(intval(sup(err_end))), intval(0)];
G_mat = Z0_mat + Z1_mat;
G_norm = max(sum(G_mat,1));
fprintf('  ||G||_op <= %.6e (Z0 = %.3e, Z1 = %.3e)\n', sup(G_norm), sup(max(sum(Z0_mat,1))), sup(max(sum(Z1_mat,1))));
if ~(sup(G_norm) < 1), error('||I-B B^dag|| is not below one'); end
ib = 2:1+N1*N2-1;  % state columns of B
aB = abs(iB);
B_mat = [sum(aB(it,1)), max(sum(aB(it,ib),1)./w_state.'); ...
         sum(wphi.*aB(ip,1)), max(max(sum(wphi.*aB(ip,ib),1)./w_state.'), intval(1))];
M = (intval(eye(2)) - G_mat) \ B_mat;
M = intval(sup(M));   % entrywise upper bounds (M >= 0 by the Neumann series)
W1t = M(1,1); W1u = M(1,2); W2t = M(2,1); W2u = M(2,2);
W3t = U_DP*W1t; W3u = U_DP*W1u;
%
%% Y bound
g_theta = abs(intval(theta).'*intval(theta) - delta_iv^2);
g_phi = wnorm_state(trace_prev(2:end) - intval(ta) - intval(Vs_at_ta)*intval(phi));
g_u_tau = Y_sup(K);
g_u_X = max(Y_sup);
Y_bvp = [W1t*g_theta + W1u*(g_phi + g_u_tau); ...
         W2t*g_theta + W2u*(g_phi + g_u_tau); ...
         W3t*g_theta + W3u*(g_phi + g_u_tau) + g_u_X];
fprintf('  g_theta = %.4e, g_phi = %.4e, g_u(tau) = %.4e, ||g_u||_X = %.4e\n', ...
  sup(g_theta), sup(g_phi), sup(g_u_tau), sup(g_u_X));
fprintf('  W1 = (%.4e, %.4e), W2 = (%.4e, %.4e), W3 = (%.4e, %.4e)\n', ...
  sup(W1t), sup(W1u), sup(W2t), sup(W2u), sup(W3t), sup(W3u));
fprintf('  Y = (%.4e, %.4e, %.4e)\n', sup(Y_bvp));
%
%% Z bound (eq:Z_BVP) and radii test (thm:BVP_existence)
ban = banorm_vec(1:K);
Ztil = @(ru) max(W_Yq*(3*(2*ban + ru).*ru));      % max over ALL rows
Zfun = @(r) [2*W1t*r(1) + W1u*Ztil(r(3)); ...
             2*W2t*r(1) + W2u*Ztil(r(3)); ...
             2*W3t*r(1) + (W3u+1)*Ztil(r(3))];
r = sup(Y_bvp);
for it_r = 1:200
  r_new = sup(Y_bvp + Zfun(intval(r))*max(r));
  if all(abs(r_new - r) <= 1e-13*r_new), r = r_new; break; end
  r = r_new;
end
r = r*(1+1e-6);
ir = intval(r);
Zr = Zfun(ir);
lhs = Y_bvp + Zr*max(ir);
bvp_ok = all(sup(lhs) < inf(ir)) && max(sup(Zr)) < 1;
fprintf('  Z(r) = (%.4e, %.4e, %.4e)\n', sup(Zr));
if bvp_ok
  fprintf('BVP PROOF SUCCESS: r0 = (r^theta, r^phi, r^u) = (%.4e, %.4e, %.4e), max Z = %.4e\n', r, max(sup(Zr)));
else
  fprintf('BVP PROOF FAILED: candidate r = (%.4e, %.4e, %.4e), max Z = %.4e\n', r, max(sup(Zr)));
end
fprintf('  margins r^i - (Y^i + Z^i max r) >= %s\n', mat2str(inf(ir - lhs).',5));

function report = intlab_runtime_check()
%INTLAB_RUNTIME_CHECK Check an initialized process without writing its cache.
% A smoke check, not a proof certificate or a full INTLAB compatibility test.
global INTLAB_CONST %#ok<GVMIS>
assert(isstruct(INTLAB_CONST) && isfield(INTLAB_CONST,'ROUNDING_SUCCESS') ...
    && isscalar(INTLAB_CONST.ROUNDING_SUCCESS) && INTLAB_CONST.ROUNDING_SUCCESS == 1, ...
    'intlabStartup:Uninitialized','INTLAB has not initialized successfully.');
assert(~isempty(which('intval')) && ~isempty(which('getround')), ...
    'intlabStartup:Path','The INTLAB arithmetic path is incomplete.');
originalRounding = getround;
restoreRounding = onCleanup(@() setround(originalRounding));
setround(0);
one = 1;
halfUlp = eps(one)/2;
setround(1); upper = one + halfUlp;
setround(-1); lower = one + halfUlp;
setround(0);
assert(upper > one && lower == one, ...
    'intlabStartup:Rounding','Directed scalar rounding failed.');
tenth = intval(1)/intval(10);
product = intval(10)*tenth;
assert(isfinite(inf(tenth)) && isfinite(sup(tenth)) ...
    && inf(tenth) < sup(tenth) && inf(product) <= 1 && sup(product) >= 1, ...
    'intlabStartup:Interval','Nonexact interval division or enclosure failed.');
assert(~intvalinit('RoundingFailure'), ...
    'intlabStartup:Rounding','INTLAB reports a rounding failure.');
report = struct('smokePassed',true,'matlabVersion',version, ...
    'computer',computer,'intlabVersion',intvalinit('version',0), ...
    'intlabRoot',fileparts(which('startintlab')), ...
    'cachePath',intvalinit('INTLABdata'), ...
    'intvalPath',which('intval'),'setroundPath',which('setround'), ...
    'tenthBounds',[inf(tenth),sup(tenth)]);
end
